import { createHash } from "node:crypto";
import { buildProductFiles } from "./product-export.mjs";

const TOKEN = process.env.GITHUB_DELIVERY_TOKEN || "";
const OWNER = process.env.GITHUB_DELIVERY_OWNER || "stalkiq";
const REPO = process.env.GITHUB_DELIVERY_REPO || "cofounderlive-deliveries";
const BASE_BRANCH = process.env.GITHUB_DELIVERY_BASE || "main";
const API = "https://api.github.com";

async function github(path, options = {}) {
  if (!TOKEN) throw new Error("GitHub delivery is not configured yet.");
  const response = await fetch(`${API}${path}`, {
    ...options,
    headers: {
      Accept: "application/vnd.github+json",
      Authorization: `Bearer ${TOKEN}`,
      "X-GitHub-Api-Version": "2022-11-28",
      "Content-Type": "application/json",
      ...(options.headers || {}),
    },
  });
  const payload = response.status === 204 ? null : await response.json().catch(() => ({}));
  if (!response.ok) {
    throw new Error(payload?.message || `GitHub request failed (${response.status})`);
  }
  return payload;
}

function encodePath(value) {
  return String(value).split("/").map(encodeURIComponent).join("/");
}

export function githubDeliveryStatus() {
  return {
    enabled: Boolean(TOKEN),
    repository: `${OWNER}/${REPO}`,
    baseBranch: BASE_BRANCH,
  };
}

export async function deliverProductToGitHub(record) {
  const product = buildProductFiles(record);
  const missionId = String(record.missionId || "").toLowerCase();
  if (!/^ep_[a-z0-9]+$/.test(missionId)) throw new Error("A valid mission is required for GitHub delivery.");
  const deliveryHash = createHash("sha256")
    .update(JSON.stringify(product.files))
    .digest("hex")
    .slice(0, 8);
  const branch = `cofounder-live/${missionId}-r${product.revision}-${deliveryHash}`;
  const head = `${OWNER}:${branch}`;
  const existing = await github(
    `/repos/${encodeURIComponent(OWNER)}/${encodeURIComponent(REPO)}/pulls?state=all&head=${encodeURIComponent(head)}&per_page=1`,
  );
  if (existing?.length) {
    return {
      repository: `${OWNER}/${REPO}`,
      repositoryUrl: `https://github.com/${OWNER}/${REPO}`,
      branch,
      folder: `products/${product.slug}`,
      pullRequestUrl: existing[0].html_url,
      pullRequestNumber: existing[0].number,
      reused: true,
    };
  }

  const baseRef = await github(
    `/repos/${encodeURIComponent(OWNER)}/${encodeURIComponent(REPO)}/git/ref/heads/${encodePath(BASE_BRANCH)}`,
  );
  const baseSha = baseRef.object.sha;
  const baseCommit = await github(
    `/repos/${encodeURIComponent(OWNER)}/${encodeURIComponent(REPO)}/git/commits/${encodeURIComponent(baseSha)}`,
  );
  const blobs = await Promise.all(Object.entries(product.files).map(async ([filePath, content]) => {
    const blob = await github(`/repos/${encodeURIComponent(OWNER)}/${encodeURIComponent(REPO)}/git/blobs`, {
      method: "POST",
      body: JSON.stringify({ content, encoding: "utf-8" }),
    });
    return {
      path: `products/${product.slug}/${filePath}`,
      mode: "100644",
      type: "blob",
      sha: blob.sha,
    };
  }));
  const tree = await github(`/repos/${encodeURIComponent(OWNER)}/${encodeURIComponent(REPO)}/git/trees`, {
    method: "POST",
    body: JSON.stringify({
      base_tree: baseCommit.tree.sha,
      tree: blobs,
    }),
  });
  const commit = await github(`/repos/${encodeURIComponent(OWNER)}/${encodeURIComponent(REPO)}/git/commits`, {
    method: "POST",
    body: JSON.stringify({
      message: `Deliver ${product.name} revision ${product.revision}`,
      tree: tree.sha,
      parents: [baseSha],
    }),
  });
  await github(`/repos/${encodeURIComponent(OWNER)}/${encodeURIComponent(REPO)}/git/refs`, {
    method: "POST",
    body: JSON.stringify({
      ref: `refs/heads/${branch}`,
      sha: commit.sha,
    }),
  });
  const capabilities = record.mvp?.googleCapabilities
    || (record.mvp?.googleCapability ? [record.mvp.googleCapability] : []);
  const pullRequest = await github(`/repos/${encodeURIComponent(OWNER)}/${encodeURIComponent(REPO)}/pulls`, {
    method: "POST",
    body: JSON.stringify({
      title: `${product.name} — product delivery r${product.revision}`,
      head: branch,
      base: BASE_BRANCH,
      body: `## Product delivery

- Mission: \`${missionId}\`
- Revision: ${product.revision}
- Google capabilities: **${capabilities.map((capability) => capability.label || capability.service).join(" + ") || "Google Cloud"}**
- Product folder: \`products/${product.slug}\`

## Included

- Self-contained interactive interface
- Validated product specification
- README and deployment instructions
- Cloud Run container configuration

Generated by Maya and Theo in Cofounder Live. Sample product data is fictional.`,
    }),
  });
  return {
    repository: `${OWNER}/${REPO}`,
    repositoryUrl: `https://github.com/${OWNER}/${REPO}`,
    branch,
    folder: `products/${product.slug}`,
    pullRequestUrl: pullRequest.html_url,
    pullRequestNumber: pullRequest.number,
    reused: false,
  };
}
